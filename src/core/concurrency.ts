/**
 * Menjalankan `fn` untuk setiap item dengan paling banyak `limit` tugas bersamaan.
 * Urutan hasil sama dengan urutan input. Error satu item tidak membatalkan yang lain
 * (hasilnya `PromiseSettledResult`), sehingga satu sumber/user gagal tidak menghentikan batch.
 */
export async function mapLimit<T, R>(
  items: readonly T[],
  limit: number,
  fn: (item: T, index: number) => Promise<R>,
): Promise<PromiseSettledResult<R>[]> {
  const results: PromiseSettledResult<R>[] = new Array(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      try {
        results[i] = { status: "fulfilled", value: await fn(items[i], i) };
      } catch (reason) {
        results[i] = { status: "rejected", reason };
      }
    }
  };
  await Promise.all(Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, worker));
  return results;
}

/** Memecah array menjadi potongan berukuran `size` (untuk batch insert). */
export function chunk<T>(items: readonly T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}
